// Base64编码函数 - 返回string（自定义实现）
std::string base64_encode(const std::string &input) {
    if (input.empty()) {
        return "";
    }

    // 使用Qt的Base64编码（标准实现，与OpenSSL兼容）
    QByteArray data(input.data(), static_cast<int>(input.length()));
    QByteArray encoded = data.toBase64(QByteArray::Base64Encoding);

    // 注意：OpenSSL的base64_encode默认不添加换行符，所以使用Base64Encoding而不是Base64UrlEncoding
    // 如果希望完全一致，可以手动移除填充的'='
    std::string result(encoded.constData(), static_cast<size_t>(encoded.length()));

    return result;
}

// Base64解码函数 - 返回string（自定义实现）
std::string base64_decode(const std::string &encoded_string) {
    if (encoded_string.empty()) {
        return "";
    }

    // Qt的fromBase64会自动处理填充字符
    QByteArray encoded(encoded_string.data(), static_cast<int>(encoded_string.length()));
    QByteArray decoded = QByteArray::fromBase64(encoded, QByteArray::Base64Encoding);

    if (decoded.isEmpty() && !encoded_string.empty()) {
        throw std::runtime_error("Failed to decode base64 data");
    }

    std::string result(decoded.constData(), static_cast<size_t>(decoded.length()));
    return result;
}

